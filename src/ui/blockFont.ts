const FALLBACK = GLYPHS['-']!;

function glyphFor(char: string): readonly string[] {
  // Fold accents (Á -> A, Ñ -> N) so translated headings still render.
  const base = char.normalize('NFD').replace(/[̀-ͯ]/g, '').toUpperCase();
  return GLYPHS[base] ?? FALLBACK;
}

/** Returns the heading as 3 lines of half-block characters. */
export function renderBlockText(text: string): string[] {
  const pixelRows: string[] = ['', '', '', '', ''];
  [...text].forEach((char, index) => {
    const glyph = glyphFor(char);
    for (let row = 0; row < 5; row++) {
      pixelRows[row] += (index > 0 ? '.' : '') + glyph[row];
    }
  });

  const lines: string[] = [];
  for (let row = 0; row < 5; row += 2) {
    const top = pixelRows[row] ?? '';
    const bottom = pixelRows[row + 1] ?? '';
    let line = '';
    for (let col = 0; col < top.length; col++) {
      const upper = top[col] === '#';
      const lower = bottom[col] === '#';
      line += upper && lower ? '█' : upper ? '▀' : lower ? '▄' : ' ';
    }
    lines.push(line);
  }
  return lines;
}
